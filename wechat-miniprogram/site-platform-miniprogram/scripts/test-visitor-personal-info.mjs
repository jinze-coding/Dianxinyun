import assert from 'node:assert/strict';
import { effectScope, ref } from 'vue';
import { useVisitorPersonalInfo } from '../src/utils/visitorPersonalInfo.ts';
const scope = effectScope();
scope.run(() => {
  const fields = { visitorCompany:ref(''),contactName:ref(''),contactPhone:ref(''),travelMode:ref('OTHER'),vehiclePlate:ref('') };
  const model = useVisitorPersonalInfo(fields);
  const saved = { available:true, rememberInfo:false, visitorCompany:'原单位',contactName:'原姓名',contactPhone:'13800000000',travelMode:'DRIVING',vehiclePlate:'沪A12345',companions:[{personName:'不应复用'}] };
  model.applyPersonalInfo({ available:false });
  assert.equal(fields.contactName.value,'');
  fields.contactName.value = '手动姓名';
  fields.contactPhone.value = '1'; fields.contactPhone.value = '';
  model.applyPersonalInfo(saved);
  assert.equal(fields.contactName.value,'手动姓名'); assert.equal(fields.contactPhone.value,'');
  assert.equal(fields.visitorCompany.value,'原单位','legacy remember=false does not disable prefill');
  assert.equal(fields.travelMode.value,'DRIVING'); assert.equal('companions' in fields,false);
  assert.equal('rememberInfo' in model,false);
  fields.visitorCompany.value = '本次修改单位'; fields.vehiclePlate.value = ''; fields.travelMode.value = 'OTHER';
  model.applyPersonalInfo({...saved,visitorCompany:'迟到的新单位'});
  assert.equal(fields.visitorCompany.value,'本次修改单位');
  assert.equal(fields.travelMode.value,'OTHER'); assert.equal(fields.vehiclePlate.value,'');
  model.resetPersonalInfo(); model.applyPersonalInfo({...saved,contactName:'新的已保存姓名'});
  assert.equal(fields.contactName.value,'新的已保存姓名'); assert.equal(fields.contactPhone.value,'13800000000');
});
scope.stop();
console.log('visitor personal info: automatic reuse, edited/cleared fields, source reset and no companions PASS');
