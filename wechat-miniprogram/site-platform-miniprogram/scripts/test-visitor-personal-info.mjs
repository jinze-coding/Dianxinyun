import assert from 'node:assert/strict';
import { effectScope, ref } from 'vue';
import { useVisitorPersonalInfo } from '../src/utils/visitorPersonalInfo.ts';
const scope = effectScope();
scope.run(() => {
  const fields = { visitorCompany:ref(''),contactName:ref(''),contactPhone:ref(''),travelMode:ref('OTHER'),vehiclePlate:ref('') };
  const model = useVisitorPersonalInfo(fields);
  const saved = { available:true, rememberInfo:true, visitorCompany:'原单位',contactName:'原姓名',contactPhone:'13800000000',travelMode:'DRIVING',vehiclePlate:'沪A12345',companions:[{personName:'不应复用'}] };
  fields.contactName.value = '手动姓名';
  fields.contactPhone.value = '1'; fields.contactPhone.value = '';
  model.applyPersonalInfo(saved);
  assert.equal(fields.contactName.value,'手动姓名');
  assert.equal(fields.contactPhone.value,'');
  assert.equal(fields.visitorCompany.value,'原单位');
  assert.equal(fields.travelMode.value,'DRIVING');
  assert.equal(model.rememberInfo.value,true);
  assert.equal('companions' in fields,false);
  model.rememberChange({detail:{value:[]}});
  model.applyPersonalInfo({...saved,visitorCompany:'迟到的新单位'});
  assert.equal(fields.visitorCompany.value,'原单位');
  assert.equal(model.rememberInfo.value,false);
  model.resetPersonalInfo();
  model.applyPersonalInfo({...saved,contactName:'新的已保存姓名'});
  assert.equal(fields.contactName.value,'新的已保存姓名');
  model.resetPersonalInfo();
  model.rememberChange({detail:{value:[]}});
  model.applyPersonalInfo(saved);
  assert.equal(model.rememberInfo.value,false);
});
scope.stop();
console.log('visitor personal info: edited fields, explicit opt-out, source reset and no companions PASS');
