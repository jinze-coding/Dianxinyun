function preview(body) {
  const move = body.operation === 'MOVE_PROJECT';
  const transfer = move || body.operation === 'COPY_PROJECT';
  const entries = body.userIds.map((id, index) => {
    const user = users.find((item) => item.id === id);
    const impact = move && index === 0 ? { projectId: 1, projectName: projects[0].projectName, userId: id, sealApprovalConfigCount: 1, totalCount: 1 } : { totalCount: 0 };
    const afterRoles = body.operation === 'REPLACE_ROLES' ? body.roleIds.map(role) : body.operation === 'REMOVE_ROLES' ? [10].filter((id) => !body.roleIds.includes(id)).map(role) : [role(10), role(20)];
    const change = { projectId: 1, projectName: projects[0].projectName, action: move ? 'REMOVED' : transfer ? 'UNCHANGED' : 'UPDATED', beforeStatus: 'ACTIVE', afterStatus: move ? null : 'ACTIVE', beforeRoles: [role(10)], afterRoles: move ? [] : transfer ? [role(10)] : afterRoles, removedPermissions: [], responsibilityImpact: impact };
    return { userId: id, username: user.username, realName: user.realName, errors: blocked && index === 0 ? ['移除后将没有任何角色，请调整选择；不会自动移出项目'] : [], projects: transfer ? [change, { ...change, projectId: 2, projectName: projects[1].projectName, action: 'ADDED', beforeRoles: [], afterRoles: body.roleSource === 'SELECTED' ? body.roleIds.map(role) : [role(10)], beforeStatus: null, afterStatus: 'ACTIVE', responsibilityImpact: { totalCount: 0 } }] : [change] };
  });
  return { confirmationToken: blocked ? null : token, changedUserCount: entries.length - (blocked ? 1 : 0), unchangedUserCount: 0, blockedUserCount: blocked ? 1 : 0, addedCount: transfer ? entries.length : 0, updatedCount: transfer ? 0 : entries.length, removedCount: move ? entries.length : 0, responsibilityCount: move ? 1 : 0, users: entries };
}
